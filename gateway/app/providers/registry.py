def _infer_transport(entry: dict) -> str:
    """按 type 推断 transport: api / web / ssh / browser。catalog 里显式写了就用显式值。"""
    if entry.get("transport"):
        return entry["transport"]
    t = entry.get("type", "")
    if t == "ssh":
        return "ssh"
    if t == "browser":
        return "browser"
    if t.startswith("web") or t == "huggingchat":
        # huggingchat 的 web API 也归到 web 类 (慢, 候选排后)
        return "web"
    return "api"


