BUILDERS: dict[str, Type[BaseProvider]] = {
    "anthropic": AnthropicProvider,
    "gemini": GeminiProvider,
    "ssh": SSHChatProvider,
    "huggingchat": HuggingChatProvider,
    # 网页转 API (Playwright 自动化, 慢, 路由时排候选后面)
    "web": WebToApiProvider,
    "web_huggingchat": HuggingChatWebProvider,
    # 浏览器本地跑 (WebLLM/WebGPU, 网关侧只能开网页, 不能直接 HTTP 调用)
    "browser": WebToApiProvider,
    # 桌面端 RPA (Windows, 模拟操作本机桌面软件)
    "desktop_cherry": CherryStudioProvider,
}
for _alias in _OAI_COMPAT_ALIASES:
    BUILDERS[_alias] = OpenAICompatibleProvider


def build_provider(config: ProviderConfig) -> BaseProvider:
    """根据 config.type 选类实例化。未知 type 默认走 OpenAI 兼容 (90% 厂商)。"""
    cls = BUILDERS.get(config.type)
    if cls is None:
        cls = OpenAICompatibleProvider
    return cls(config)


