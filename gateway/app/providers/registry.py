def catalog_to_provider_config(entry: dict) -> ProviderConfig:
    """把 catalog 元数据转成 ProviderConfig (供自动配置/Web UI 用)。

    - enabled_by_default=False 的条目默认 disabled (用户手动开)。
    - type=unsupported 的不实例化 (调用方应跳过)。
    """
    if entry.get("type") == "unsupported":
        raise ValueError(f"{entry['name']} 是 unsupported 类型, 不能 build 成 provider")
    return ProviderConfig(
        name=entry["name"],
        type=entry["type"],
        base_url=entry.get("default_base_url", ""),
        models=list(entry.get("default_models", [])),
        priority=int(entry.get("priority", 100)),
        cost_tier=entry.get("cost_tier", "low"),
        enabled=bool(entry.get("enabled_by_default", True)),
        extra={},
    )


def zero_config_entries() -> list[dict]:
    """Dashboard 分组: 🔥 零配置免费。
    排序: verified_ok > needs_local/needs_ssh/needs_browser > unverified > verified_bad。
    真正能用的排最前, 跑不通的沉底。
    """
    _ORDER = {"verified_ok": 0, "needs_local": 1, "needs_ssh": 2, "needs_browser": 3,
              "unverified": 4, "verified_bad": 5}
    return sorted(
        [e for e in FREE_PROVIDER_CATALOG if e.get("is_zero_config") and e.get("type") != "unsupported"],
        key=lambda e: (_ORDER.get(e.get("verified_status", "unverified"), 9), e.get("priority", 999)),
    )


