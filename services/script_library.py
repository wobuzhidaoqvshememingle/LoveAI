_usage_lock = threading.Lock()
# scene -> list[已用 text]（保留最近 N 条用于去重）
_recent: dict[str, list[str]] = {}
_DEDUP_KEEP = 6   # 每个场景记住最近 6 条，保证连续 3 次不重复


def reset_usage() -> None:
    """换一个人 / 新会话时清空去重记录。"""
    with _usage_lock:
        _recent.clear()


