_NAME_SLOTS = ("你", "我", "宝贝", "亲爱的", "宝宝", "darling", "对方")

# --------------------------------------------------------------------------- #
# 话题守卫：只有 last_topic 确实像"名词短语"时才拼尾句
# --------------------------------------------------------------------------- #
# 背景（实测第一因）：auto_strategy_pipeline._build_refine_context 把对方最近
# 一条消息的【整句原文】截 20 字当作 last_topic 传进来，下游却按名词短语使用，
# 拼出「…。对了，你今天怎么都不找我，是不是不在乎我了那事后来呢？」这类语法
# 破碎、与上文语义重复的尾句。抽不到合格话题时，宁可不拼。
_TOPIC_MAX_LEN = 12
_TOPIC_PUNCT = "，。！？；：、,.!?;:"
_TOPIC_MARKERS = ("是不是", "怎么", "为什么", "什么", "吗", "呢")


def _is_topic_phrase(text: str) -> bool:
    """text 是否像可安全嵌入「{topic}那事」的名词性话题。

    整句原话（含标点/疑问词或过长）一律判否 ⇒ 调用方跳过拼尾句。
    """
    t = (text or "").strip()
    if not t or len(t) > _TOPIC_MAX_LEN:
        return False
    if any(ch in _TOPIC_PUNCT for ch in t):
        return False
    if any(w in t for w in _TOPIC_MARKERS):
        return False
    return True


def refine_script(template: str, context: Optional[dict] = None) -> str:
    """根据当前聊天上下文微调一条话术。

    context 可含：
      nickname   ：对方称呼（如"小雨"）→ 替换模板里泛称；
      user_name  ：我方称呼；
      last_topic ：对方之前提过的事（如"加班"），织入细节；
      mood       ：对方当前情绪（开心/低落/生气/平静），据此调语气；
      pet_name   ：双方专属昵称（如"笨蛋"），优先使用。

    不是直接复制模板：会做①换称呼 ②织入上一次提到的细节 ③按情绪调语气。
    """
    if not template:
        return ""
    ctx = context or {}
    out = str(template)

    # 1) 换称呼：pet_name > nickname
    pet = (ctx.get("pet_name") or "").strip()
    nick = (ctx.get("nickname") or "").strip()
    if pet:
        # 把"你"换成更亲密的称呼（仅句首/称呼位，避免全替换语病）
        out = re.sub(r"(?<![是要跟和把对为给向叫])你(?![好会能])", pet, out, count=1)
    elif nick:
        # 在句末或停顿处自然带上对方名字
        if nick not in out:
            out = out.rstrip("。！!?？") + f"，{nick}。"

    # 2) 织入上一次提到的细节（仅当 last_topic 是合格的名词性话题时才拼）
    topic = (ctx.get("last_topic") or "").strip()
    if topic and _is_topic_phrase(topic) and topic not in out:
        # 简短地把对方之前提过的事接进来
        tail = {
            "开心": f"对了，{topic}后来怎么样了？",
            "低落": f"那个{topic}的事，要是想说说我在。",
            "生气": f"先不说别的，{topic}那事咱们回头好好捋。",
        }.get((ctx.get("mood") or "平静"), f"对了，{topic}那事后来呢？")
        out = out.rstrip("。！!?？") + "。" + tail

    # 3) 按情绪调语气
    mood = (ctx.get("mood") or "").strip()
    if mood == "生气":
        # 对方在气头上，去掉调侃，放软
        out = out.replace("哈哈哈", "").strip()
        if not out.endswith(("。", "！", "？")):
            out += "。"
    elif mood == "低落":
        # 低落时不嬉皮笑脸，去掉"幽默"尾巴
        out = re.sub(r"[~～]", "", out)
    elif mood == "开心":
        # 开心时加一点轻快
        if not out.endswith(("！", "~", "～")):
            out += "！"

    return out.strip()


