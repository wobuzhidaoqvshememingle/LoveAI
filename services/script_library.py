def _scene_list(scene: str) -> list[dict]:
    return SCENES.get(scene, [])


def list_scenes() -> list[str]:
    return list(SCENES.keys())


def pick_scripts(scene: str, k: int = 3, style: Optional[str] = None,
                 length: Optional[str] = None,
                 rng: Optional[random.Random] = None) -> list[str]:
    """从某场景挑 k 条话术。

    - 先按 style / length 过滤；
    - 排除最近用过的（保证连续多次调用不重复）；
    - 过滤后不够则放宽条件补齐；
    - 返回 text 字符串列表。
    """
    pool = _scene_list(scene)
    if not pool:
        return []

    r = rng or random.Random()
    with _usage_lock:
        used = set(_recent.get(scene, []))

    def _filter(items: list[dict]) -> list[dict]:
        out = []
        for it in items:
            if style and it.get("style") != style:
                continue
            if length and it.get("length") != length:
                continue
            out.append(it)
        return out

    candidates = _filter(pool)
    # 排除最近用过的
    fresh = [it for it in candidates if it["text"] not in used]
    if len(fresh) < k:
        # 放宽：不按 style/length，只排除用过的
        fresh = [it for it in pool if it["text"] not in used]
    if not fresh:
        # 全用过了，清空该场景记录重来
        with _usage_lock:
            _recent[scene] = []
        fresh = list(pool)

    picks = r.sample(fresh, min(k, len(fresh)))
    picked_texts = [p["text"] for p in picks]

    with _usage_lock:
        rec = _recent.setdefault(scene, [])
        rec.extend(picked_texts)
        # 只保留最近 N 条
        if len(rec) > _DEDUP_KEEP:
            _recent[scene] = rec[-_DEDUP_KEEP:]
    return picked_texts


