def _apply_persona_lens(text: str, persona_type: Optional[str]) -> str:
    """按对方人格类型做语气微调；未知类型原样返回。"""
    if not persona_type:
        return text
    rules = _PERSONA_LENSES.get(persona_type)
    if not rules:
        return text
    out = text
    for old, new in rules:
        out = out.replace(old, new)
    return out


