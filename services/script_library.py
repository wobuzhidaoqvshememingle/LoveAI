# person_id -> scene -> [最近用过的 text]
_person_usage: dict[str, dict[str, list[str]]] = {}
_PERSON_DEDUP_KEEP = 6


def _dedupe_recent(person_id: Optional[str], scene: str,
                   candidates: list[str], n: int = 3) -> list[str]:
    """从候选话术中排除该人最近 n 次（按记录保留窗口）已用过的同场景话术。

    Args:
        person_id: 对方人物 ID；None 时不去重（保持旧行为）。
        scene: 场景名。
        candidates: 候选 text 列表。
        n: 保留参数（语义上"最近 n 次"），实际排除窗口由 _PERSON_DEDUP_KEEP 控制。

    Returns:
        过滤后的候选列表；若过滤后为空，返回原列表（宁可用过也别没的选）。
    """
    if not person_id:
        return list(candidates)
    with _usage_lock:
        used = set(_person_usage.get(person_id, {}).get(scene, []))
    fresh = [c for c in candidates if c not in used]
    return fresh or list(candidates)


def record_usage(person_id: Optional[str], scene: str, texts: list[str]) -> None:
    """记录某人在某场景用过的话术（供后续 _dedupe_recent 排除）。"""
    if not person_id or not texts:
        return
    with _usage_lock:
        bucket = _person_usage.setdefault(person_id, {})
        rec = bucket.setdefault(scene, [])
        rec.extend(t for t in texts if t)
        if len(rec) > _PERSON_DEDUP_KEEP:
            bucket[scene] = rec[-_PERSON_DEDUP_KEEP:]


def reset_person_usage(person_id: Optional[str] = None) -> None:
    """清空某人的跨会话去重记录；不传 person_id 则清空全部。"""
    with _usage_lock:
        if person_id is None:
            _person_usage.clear()
        else:
            _person_usage.pop(person_id, None)


